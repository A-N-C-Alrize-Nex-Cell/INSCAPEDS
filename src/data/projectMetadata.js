/**
 * Match a raw project title or folder name against the portfolio registry.
 * Returns { title, location, status, area, category } if matched, or default fallback.
 *
 * Picks the entry whose matching keyword is LONGEST (most specific), not the
 * first one found in array order. Several registry entries share a generic,
 * single-word keyword that's just a city name (e.g. "ranchi", "durgapur",
 * "taki") — with first-match-wins, a short generic keyword earlier in the
 * array could steal a match that a later, far more specific keyword (e.g.
 * "samriddhi park", "aircraft museum") was clearly meant for. Scoring by
 * keyword length instead means the specific match always wins regardless of
 * array position.
 */
export function getProjectMetadata(rawTitle = "") {
  const norm = String(rawTitle).toLowerCase().trim();
  if (!norm) return null;

  let best = null;
  let bestLen = 0;
  for (const item of projectRegistry) {
    for (const kw of item.keywords) {
      const kwLower = kw.toLowerCase();
      if ((norm.includes(kwLower) || kwLower.includes(norm)) && kwLower.length > bestLen) {
        best = item;
        bestLen = kwLower.length;
      }
    }
  }
  return best;
}
